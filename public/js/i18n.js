let current = 'en';

export function setLocale(language) {
  current = STRINGS[language] ? language : 'en';
  document.documentElement.lang = current;
}

export function getLocale() {
  return current;
}

/** Looks a key up in the active locale, falling back to English. */
export function t(key, vars) {
  const value = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : match,
  );
}

export function interestLabel(id) {
  return STRINGS[current]?.interest?.[id] ?? STRINGS.en.interest[id] ?? id;
}

/** Applies data-i18n / data-i18n-placeholder attributes across the document. */
export function applyTranslations(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  }
}
